// Run with Playwright installed, against an initialized disposable WordPress site.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const origin = process.env.HTECL_QA_URL;
const password = process.env.HTECL_QA_PASSWORD;
const zip = process.env.HTECL_QA_ZIP;
const artifacts = process.env.HTECL_QA_ARTIFACTS || '/tmp/htecl-browser-evidence';
if (!origin || !password) throw new Error('Set HTECL_QA_URL and HTECL_QA_PASSWORD. Use a disposable installation.');
const pagePath = (name, query = '') => `${origin}/wp-admin/admin.php?page=htecl-${name}${query}`;
const url = path => `${origin}${path}`;
const must = async (locator) => locator.first().waitFor({ state: 'visible', timeout: 8000 });
const report = step => console.log(`PASS: ${step}`);

(async () => {
  await fs.mkdir(artifacts, { recursive: true });
  const browser = await chromium.launch();
  const admin = await browser.newPage({ acceptDownloads: true, viewport: { width: 1440, height: 1000 } });
  admin.setDefaultTimeout(12000);
  const errors = [];
  for (const page of [admin]) page.on('pageerror', e => errors.push(e.message));
  try {
    await admin.goto(url('/wp-login.php'));
    await admin.locator('#user_login').fill(process.env.HTECL_QA_USER || 'qa_admin');
    await admin.locator('#user_pass').fill(password);
    await admin.locator('#wp-submit').click();
    await must(admin.locator('#wpadminbar'));
    if (zip) {
      await admin.goto(url('/wp-admin/plugin-install.php?tab=upload'));
      await admin.locator('#pluginzip').setInputFiles(zip);
      await admin.getByRole('button', { name: 'Install Now' }).click();
      await admin.getByRole('link', { name: 'Activate Plugin', exact: true }).click();
      await must(admin.getByText('Plugin activated.', { exact: true }));
      report('Dashboard upload, install and activation of the release-candidate ZIP');
    }
    await admin.goto(pagePath('overview', '&setup=1'));
    await admin.getByLabel('Step 2 · Business name').fill('HTECH QA Studio');
    await admin.getByLabel('Step 3 · Business email').fill('office@example.test');
    await admin.getByLabel('Step 4 · WhatsApp number (optional)').fill('+2348021234567');
    await admin.getByLabel('Step 5 · First enquiry form').fill('Project enquiries');
    await admin.getByRole('button', { name: 'Save and show shortcode' }).click();
    const code = await admin.locator('.htecl-admin code').first().textContent();
    const formId = Number(code.match(/id="(\d+)"/)[1]);
    await admin.getByRole('button', { name: 'Finish setup' }).click();
    await must(admin.getByText('Setup closed.', { exact: false }));
    await admin.goto(pagePath('forms', `&id=${formId}`));
    await admin.getByRole('button', { name: 'Add field' }).click();
    const field = admin.locator('.htecl-builder').last();
    await field.getByLabel('Label', { exact: true }).fill('Where should we start?');
    await field.getByLabel('Type', { exact: true }).selectOption('select');
    await field.getByLabel('Dropdown options (one per line)').fill('Consulting\nInstallation');
    await admin.getByRole('button', { name: 'Save form' }).click();
    await must(admin.getByText('Form saved.', { exact: true }));
    report('Onboarding, stored shortcode, form editing and dropdown builder');
    await admin.goto(url('/wp-admin/post-new.php?post_type=page'), {waitUntil:'domcontentloaded'});
    // Gutenberg's code editor still saves native block markup.
    await admin.evaluate(() => {
      wp.data.dispatch('core/edit-post').switchEditorMode('text');
    }).catch(() => {});
    await admin.evaluate(async shortcode => {
      for (let i = 0; i < 50 && !window.wp?.data?.select('core/editor')?.getCurrentPostId(); i++) await new Promise(r => setTimeout(r, 100));
      const editor = wp.data.dispatch('core/editor');
      editor.editPost({ title: 'QA Enquiry', status: 'publish', content: `<!-- wp:shortcode -->\n${shortcode}\n<!-- /wp:shortcode -->\n<!-- wp:shortcode -->\n[htech_whatsapp]\n<!-- /wp:shortcode -->` });
      await editor.savePost();
      if (wp.data.select('core/editor').getEditedPostAttribute('status') !== 'publish') throw new Error('Page not published');
    }, code);
    const permalink = await admin.evaluate(() => wp.data.select('core/editor').getPermalink());
    assert.ok(permalink && !permalink.includes('%pagename%'));
    const visitor = await browser.newPage({ viewport: { width: 390, height: 844 } });
    visitor.on('pageerror', e => errors.push(e.message));
    const landing = new URL(permalink); landing.searchParams.set('utm_source','newsletter'); landing.searchParams.set('utm_campaign','qa_launch');
    await visitor.goto(landing.href);
    await must(visitor.getByRole('link', { name: 'Chat on WhatsApp' }));
    const form = visitor.locator('form.htecl-public');
    await form.getByLabel('Full name').fill('Ada QA');
    await form.getByLabel('Email address').fill('ada@example.test');
    await form.getByLabel('Phone number').fill('0802 123 4567');
    await form.getByLabel('How can we help?').fill('A genuine test enquiry for installation.');
    await form.getByLabel('Where should we start?').selectOption('Installation');
    assert.ok(await form.evaluate(el => el.getBoundingClientRect().right <= window.innerWidth));
    await visitor.screenshot({ path: `${artifacts}/mobile-form.png`, fullPage: true });
    await visitor.waitForTimeout(2200);
    const body = await form.evaluate(el => Object.fromEntries(new FormData(el)));
    const endpoint = await form.getAttribute('action');
    const csrf = await visitor.request.post(endpoint, { form: { ...body, _wpnonce:'invalid' }, maxRedirects: 0 });
    assert.match(decodeURIComponent(csrf.headers().location), /form session expired/);
    const spam = await visitor.request.post(endpoint, { form: { ...body, website_confirm:'bot' }, maxRedirects: 0 });
    assert.match(decodeURIComponent(spam.headers().location), /wait a moment/);
    await form.getByRole('button', { name: 'Send enquiry' }).click();
    await must(visitor.getByText('Thank you. Your enquiry has been received.', { exact: true }));
    const duplicate = await visitor.request.post(endpoint, { form: body, maxRedirects: 0 });
    assert.match(decodeURIComponent(duplicate.headers().location), /already have been recorded/);
    await visitor.goto(pagePath('leads'));
    assert.match(visitor.url(), /wp-login\.php/);
    report('Gutenberg shortcode, mobile form, attribution, submission, nonce and spam checks, duplicate protection, anonymous admin denial');
    await admin.goto(pagePath('leads'));
    await admin.getByRole('link', { name: 'Ada QA', exact: true }).click();
    const leadUrl = admin.url();
    await must(admin.getByText('qa_launch', { exact: true }));
    await must(admin.locator('.htecl-card p').filter({ hasText: 'Where should we start?' }).filter({ hasText: 'Installation' }));
    await admin.getByLabel('Full name').fill('Ada QA Updated');
    await admin.getByLabel('Stage', { exact: true }).selectOption('qualified');
    await admin.getByLabel('Assigned user').selectOption({ label: await admin.locator('select[name=assigned] option').nth(1).textContent() });
    await admin.getByRole('button', { name: 'Save lead' }).click();
    const wa = await admin.getByRole('link', { name: 'Open WhatsApp conversation' }).getAttribute('href');
    assert.match(wa, /^https:\/\/wa\.me\/2348021234567\?text=/);
    assert.match(decodeURIComponent(wa), /Ada QA Updated/);
    await admin.getByLabel('Private note').fill('Private QA note');
    await admin.getByRole('button', { name: 'Add note' }).click();
    await must(admin.getByText('Private QA note', { exact: true }));
    await admin.getByLabel('Due date').fill('2030-12-01');
    await admin.getByLabel('Follow-up note').fill('Call about project');
    await admin.getByRole('button', { name: 'Schedule follow-up' }).click();
    await must(admin.getByText('Call about project', { exact: true }));
    await admin.goto(pagePath('followups', '&when=upcoming'));
    await admin.getByRole('button', { name: 'Mark complete' }).click();
    await admin.goto(pagePath('followups', '&when=done'));
    await must(admin.getByText('Completed', { exact: true }).last());
    await admin.goto(pagePath('pipeline', '&mode=table'));
    await admin.locator('select[name=status]').first().selectOption('converted');
    await admin.getByRole('button', { name: 'Move', exact: true }).first().click();
    await admin.goto(leadUrl);
    await must(admin.getByText('Stage changed from Qualified to Converted', { exact: true }));
    await admin.goto(pagePath('analytics'));
    await must(admin.getByText('100%', { exact: true }));
    await must(admin.getByText('qa_launch', { exact: true }));
    await admin.screenshot({ path: `${artifacts}/analytics.png`, fullPage: true });
    await admin.evaluate(() => { window.print = () => { window.hteclQAPrinted = true; }; });
    await admin.getByRole('button', {name:'Print report'}).click();
    assert.equal(await admin.evaluate(() => window.hteclQAPrinted), true);
    await admin.goto(pagePath('leads'));
    await admin.getByRole('checkbox', { name: 'Select lead' }).first().check();
    const downloaded = admin.waitForEvent('download');
    await admin.getByRole('button', { name: 'Export selected' }).click();
    const download = await downloaded;
    const csv = await fs.readFile(await download.path(),'utf8');
    assert.match(csv,/Ada QA Updated/);
    assert.doesNotMatch(csv,/Private QA note/);
    report('Lead edits and assignment, notes, follow-up completion, persistent stage move, WhatsApp URL, real analytics, selected CSV export');
    await admin.goto(pagePath('tools'));
    const file = admin.locator('input[type=file]');
    await file.setInputFiles({ name:'unsafe.php', mimeType:'text/plain', buffer:Buffer.from('name\nNo\n') });
    await admin.getByRole('button', { name: 'Upload for mapping' }).click();
    await must(admin.getByText('Upload a valid .csv file.', { exact:true }));
    await file.setInputFiles({ name:'leads.csv', mimeType:'text/csv', buffer:Buffer.from('name,email\nDuplicate,ada@example.test\nImported,imported@example.test\nInvalid,bad\n') });
    await admin.getByRole('button', { name: 'Upload for mapping' }).click();
    await admin.getByRole('button', { name: 'Validate and preview' }).click();
    await must(admin.getByText('Row 2: possible duplicate; skipped.', { exact:true }));
    await must(admin.getByText('Row 4: Invalid email or phone.', { exact:true }));
    await admin.getByRole('button', { name: 'Import valid rows' }).click();
    await must(admin.getByText('1 imported, 2 skipped and 0 could not be saved.', { exact:true }));
    await admin.goto(pagePath('leads', '&q=Imported'));
    await admin.getByRole('link', { name:'Imported', exact:true }).click();
    await admin.getByText('Permanently delete this lead', { exact:true }).click();
    await admin.getByRole('button', { name:'Delete lead', exact:true }).click();
    await must(admin.getByText('1 lead(s) deleted.', { exact:true }));
    await admin.goto(pagePath('whatsapp'));
    await admin.getByLabel('Button label').fill('Talk with our team');
    await admin.getByRole('button', { name:'Save settings' }).click();
    await visitor.goto(permalink);
    await must(visitor.getByRole('link', { name:'Talk with our team' }));
    const second = visitor.locator('form.htecl-public');
    await second.getByLabel('Full name').fill('Second enquiry from Ada');
    await second.getByLabel('Email address').fill('ada@example.test');
    await second.getByLabel('How can we help?').fill('A different enquiry with the same email.');
    await visitor.waitForTimeout(2200);
    await second.getByRole('button',{name:'Send enquiry'}).click();
    await must(visitor.getByText('Thank you. Your enquiry has been received.',{exact:true}));
    await admin.goto(leadUrl);
    const duplicateSection = admin.locator('section.htecl-card').filter({has:admin.getByRole('heading',{name:'Possible duplicates'})});
    await duplicateSection.getByText('I reviewed both records and want to keep this lead.',{exact:true}).click();
    await duplicateSection.getByRole('button',{name:'Merge into this lead'}).click();
    await must(admin.getByText('Records merged; history and original submission details were preserved.',{exact:true}));
    await must(admin.getByText('Archived record #',{exact:false}).first());
    report('Reviewed duplicate merge retains the original lead and archives the second submission');
    await admin.goto(pagePath('forms', `&id=${formId}`));
    await admin.getByText('Remove this form; keep the leads it captured', { exact:true }).click();
    await admin.getByRole('button',{ name:'Delete form' }).click();
    await must(admin.getByText('Form removed. Existing leads were kept.', { exact:true }));
    await admin.goto(leadUrl);
    await must(admin.getByText('Removed form #'+formId, { exact:false }));
    report('Unsafe upload rejected, CSV mapping and review, import, deletion, live settings update, deleting form retains lead');
    await admin.goto(url('/wp-admin/plugins.php'));
    await admin.locator('tr[data-slug=htech-leadflow]').getByRole('link', { name:'Deactivate' }).click();
    await admin.locator('tr[data-slug=htech-leadflow]').locator('a[href*="action=activate"]').click();
    await admin.goto(leadUrl);
    await must(admin.getByText('Private QA note', { exact:true }));
    const leadId = new URL(leadUrl).searchParams.get('id');
    const badAdmin = await admin.request.post(url('/wp-admin/admin-post.php'), {form:{action:'htecl_admin',op:'stage',id:leadId,status:'lost',htecl_nonce:'bad'},maxRedirects:0});
    assert.equal(badAdmin.status(),403);
    if (process.env.HTECL_QA_SUBSCRIBER_PASSWORD) {
      const limited = await browser.newPage();
      await limited.goto(url('/wp-login.php'));
      await limited.locator('#user_login').fill('qa_subscriber');
      await limited.locator('#user_pass').fill(process.env.HTECL_QA_SUBSCRIBER_PASSWORD);
      await limited.locator('#wp-submit').click();
      const blocked = await limited.goto(leadUrl);
      assert.equal(blocked.status(),403);
      const denied = await limited.request.post(url('/wp-admin/admin-post.php'), { form:{action:'htecl_admin',op:'stage',id:leadId,status:'lost'},maxRedirects:0 });
      assert.equal(denied.status(),403);
      report('Signed-in subscriber denied lead read and mutation; administrator mutation rejects an invalid nonce');
    }
    await admin.setViewportSize({width:390,height:844});
    await admin.goto(pagePath('pipeline'));
    await must(admin.getByRole('link',{name:'Ada QA Updated',exact:true}));
    const board = admin.locator('.htecl-board');
    assert.ok(await board.evaluate(el => el.getBoundingClientRect().right <= window.innerWidth));
    await admin.screenshot({path:`${artifacts}/mobile-pipeline.png`,fullPage:true});
    report('Mobile pipeline fits the viewport; converted lead renders in the board');
    assert.deepEqual(errors,[]);
    report('Dashboard deactivation/reactivation retains lead and note; no uncaught browser errors');
  } catch (err) {
    await admin.screenshot({ path:`${artifacts}/failure.png`,fullPage:true }).catch(() => {});
    throw err;
  } finally { await browser.close(); }
})().catch(err => { console.error(err); process.exitCode=1; });
